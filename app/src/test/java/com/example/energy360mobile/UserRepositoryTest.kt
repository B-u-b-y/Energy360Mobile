package com.example.energy360mobile

import com.example.energy360mobile.databases.userData.UserDao
import com.example.energy360mobile.databases.userData.UserEntity
import com.example.energy360mobile.databases.userData.UserFirebaseDataSource
import com.example.energy360mobile.databases.userData.UserRepository
import io.mockk.coEvery
import io.mockk.coVerify
import io.mockk.every
import io.mockk.mockk
import io.mockk.verify
import kotlinx.coroutines.runBlocking
import org.junit.Assert.assertEquals
import org.junit.Test

/**
 * Unit tests for [UserRepository].
 * Verifies the coordination between local Room database and remote Firebase source.
 */
class UserRepositoryTest {

    private val dao = mockk<UserDao>(relaxed = true)
    private val firebase = mockk<UserFirebaseDataSource>(relaxed = true)
    private val repository = UserRepository(dao, firebase)

    /**
     * Verifies that [UserRepository.syncUserFromCloud] fetches a user from Firebase
     * and inserts it into the local database if found.
     */
    @Test
    fun syncUserFromCloud_whenUserExists_insertsIntoDao() = runBlocking {
        val user = UserEntity("u123", "John Doe", "pass123", "john@example.com", 123456789L)
        coEvery { firebase.fetchUser("u123") } returns user

        repository.syncUserFromCloud("u123")

        coVerify { dao.insert(user) }
    }

    /**
     * Verifies that [UserRepository.syncUserFromCloud] does not call the DAO if the user
     * is not found in Firebase.
     */
    @Test
    fun syncUserFromCloud_whenUserNotFound_doesNotInsert() = runBlocking {
        coEvery { firebase.fetchUser(any()) } returns null

        repository.syncUserFromCloud("nonexistent")

        coVerify(exactly = 0) { dao.insert(any()) }
    }

    /**
     * Verifies that [UserRepository.insertUser] saves the user to Firebase first,
     * updates the user ID with the one generated by Firebase, and then saves locally.
     */
    @Test
    fun insertUser_savesToCloudThenLocal() = runBlocking {
        val user = UserEntity("", "Jane Doe", "securePass", "jane@example.com", 987654321L)
        val mockRef = mockk<com.google.firebase.firestore.DocumentReference>()
        every { mockRef.id } returns "firebase_gen_id"
        coEvery { firebase.saveUser(any()) } returns mockRef

        repository.insertUser(user)

        assertEquals("firebase_gen_id", user.id)
        coVerify { firebase.saveUser(any()) }
        coVerify { dao.insert(user) }
    }

    /**
     * Verifies that [UserRepository.removeUser] clears the local database.
     */
    @Test
    fun removeUser_clearsLocalData() = runBlocking {
        repository.removeUser()
        coVerify { dao.clearAll() }
    }

    /**
     * Verifies that [UserRepository.checkIfEmailExists] delegates to the Firebase source.
     */
    @Test
    fun checkIfEmailExists_delegatesToFirebase() {
        val user = UserEntity("", "", "", "test@test.com", 0L)
        every { firebase.insertUserData(user) } returns true

        val result = repository.checkIfEmailExists(user)

        assertEquals(true, result)
        verify { firebase.insertUserData(user) }
    }

    /**
     * Verifies that [UserRepository.fetchUserData] returns the user entity from Firebase.
     */
    @Test
    fun fetchUserData_returnsUserFromFirebase() {
        val email = "john@example.com"
        val user = UserEntity("u123", "John", "pass", email, 1000L)
        every { firebase.fetchUserData(email) } returns user

        val result = repository.fetchUserData(email)

        assertEquals(user, result)
        verify { firebase.fetchUserData(email) }
    }
}
